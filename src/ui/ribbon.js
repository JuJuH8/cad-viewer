const svg = (name) => `<svg viewBox="0 0 24 24" aria-hidden="true">${I[name] || ''}</svg>`;

export function renderRibbon(host, current = 0) {
  const tabs = RIBBON.map((t, i) => `<button class="rtab ${i === current ? 'active' : ''}" data-tab="${i}">${t.tab}</button>`).join('');
  // Outils principaux (les premiers du groupe) avec libellé ; au-delà, petites icônes sur deux rangs (info-bulle).
  const btn = ([cmd, label, icon, key], small) => `<button ${cmd.startsWith('@') ? `data-action="${cmd.slice(1)}"` : `data-cmd="${cmd}"`} title="${label} (${key})"${small ? ` aria-label="${label}"` : ''}>${svg(icon)}${small ? '' : `<span>${label}</span>`}</button>`;
  const panel = RIBBON[current].groups.map((g) => {
    const big = g.items.length <= 5 ? g.items : g.items.slice(0, 3);
    const rest = g.items.slice(big.length);
    return `<div class="group"><div class="tools">${big.map((it) => btn(it, false)).join('')}${rest.length ? `<div class="small">${rest.map((it) => btn(it, true)).join('')}</div>` : ''}</div><span class="group-label">${g.label}</span></div>`;
  }).join('');
  host.innerHTML = `<div class="rtabs">${tabs}</div><div class="rpanel">${panel}</div>`;
}
